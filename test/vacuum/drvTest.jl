@testset "Near derivative kernels" begin
    QI = Rational{BigInt}
    nerK(s, R, frq, der) = GilaElectromagnetics.drvNer!(zeros(ComplexDF64, 3, 3, length(GilaElectromagnetics.drvGam(der)), 1), [QI.(R .* s)], QI.(s), frq, der)
    for ((s, R, ks, der), ent) in nerGld
        K = nerK(s, R, ks / (2π * Float64(maximum(s))), der)
        for (a, b, j, re, im) in ent
            @test abs(K[a, b, j, 1] - ComplexDF64(Double64(re), Double64(im))) <= 1e-28 * maximum(abs, K)
        end
    end
    for s in ((1, 1, 1) .// 1, (1, 1, 8) .// 8), der in (1, 3)
        @test all(iszero, nerK(s, (0, 0, 0), 0.1, der))
    end
    # (Δ + k^2) psi = -1/f^2 inside the source cell, 0 outside: the trace of K^(2e_a) closes on k^2 K^0
    for (s, R) in (((1, 1, 1) .// 1, (0, 0, 0)), ((1, 1, 8) .// 8, (1, 1, 0)))
        frq = 0.25; K2 = nerK(s, R, frq, 2); K0 = nerK(s, R, frq, 0)
        res = K2[:, :, 1, 1] + K2[:, :, 4, 1] + K2[:, :, 6, 1] + (2 * Double64(π) * frq)^2 * K0[:, :, 1, 1]
        all(iszero, R) && (res += (2 * Double64(π))^2 * [a == b for a in 1:3, b in 1:3])
        @test maximum(abs, res) <= 1e-29 * maximum(abs, K2)
    end
    @test_throws ArgumentError nerK((1, 1, 1) .// 1, (1 // 2, 0, 0), 0.1, 0)
end
